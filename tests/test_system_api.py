async def test_metrics_404_when_no_token(monkeypatch):
    monkeypatch.setenv("METRICS_TOKEN", "")
    get_settings.cache_clear()
    with pytest.raises(HTTPException) as exc:
        await system_api.prometheus_metrics(credentials=None)
    assert exc.value.status_code == 404


async def test_metrics_401_on_wrong_token(monkeypatch):
    from fastapi.security import HTTPAuthorizationCredentials

    monkeypatch.setenv("METRICS_TOKEN", "right-token")
    get_settings.cache_clear()
    bad = HTTPAuthorizationCredentials(scheme="Bearer", credentials="wrong")
    with pytest.raises(HTTPException) as exc:
        await system_api.prometheus_metrics(credentials=bad)
    assert exc.value.status_code == 401


async def test_metrics_render_format(monkeypatch):
    from fastapi.security import HTTPAuthorizationCredentials

    monkeypatch.setenv("METRICS_TOKEN", "right-token")
    get_settings.cache_clear()
