# ── JWT auto-generation ─────────────────────────────────────────────────────

def test_jwt_secret_autogenerated_and_stable(monkeypatch, tmp_path):
    from src.configs.settings import Settings

    secret_file = tmp_path / "jwt_secret"
    monkeypatch.setenv("SUBAGENTS_JWT_SECRET_FILE", str(secret_file))
    monkeypatch.setenv("AUTH_DISABLED", "false")
    monkeypatch.setenv("JWT_SECRET", "change-me-in-production")

    s1 = Settings()
    assert s1.jwt_secret != "change-me-in-production"
    assert len(s1.jwt_secret) >= 32
    assert secret_file.exists()
    assert (secret_file.stat().st_mode & 0o777) == 0o600
    # Stable across restarts.
    assert Settings().jwt_secret == s1.jwt_secret


def test_explicit_jwt_secret_wins(monkeypatch, tmp_path):
    from src.configs.settings import Settings

    monkeypatch.setenv("SUBAGENTS_JWT_SECRET_FILE", str(tmp_path / "jwt_secret"))
    monkeypatch.setenv("AUTH_DISABLED", "false")
    monkeypatch.setenv("JWT_SECRET", "my-real-secret-set-by-the-operator!")
    assert Settings().jwt_secret == "my-real-secret-set-by-the-operator!"
    assert not (tmp_path / "jwt_secret").exists()


# ── /events connection cap ──────────────────────────────────────────────────

async def test_events_connection_cap(monkeypatch):
    from src.api.events import events
    from src.services.event_broker import get_broker, reset_broker

    monkeypatch.setenv("EVENTS_MAX_CONNECTIONS_PER_USER", "2")
    get_settings.cache_clear()
    reset_broker()
    broker = get_broker()
    broker.subscribe("u1")
    broker.subscribe("u1")
    broker.subscribe("someone-else")  # other users don't count against u1

    with pytest.raises(HTTPException) as exc:
        await events(user_id="u1")
    assert exc.value.status_code == 429

    # A different user still connects fine.
    response = await events(user_id="u2")
    assert response is not None
    reset_broker()
