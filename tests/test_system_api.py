from types import SimpleNamespace

import pytest
from fastapi import HTTPException

from src.api import system as system_api
from src.configs.settings import get_settings
from src.services import metrics


@pytest.fixture(autouse=True)
def fresh(monkeypatch, tmp_path):
    metrics.reset()
    get_settings.cache_clear()
    monkeypatch.setenv("SUBAGENTS_MCP_TOKENS", str(tmp_path / "tokens.json"))
    yield
    metrics.reset()
    get_settings.cache_clear()


class _OkConn:
    async def __aenter__(self):
        return self

    async def __aexit__(self, *args):
        return False

    async def execute(self, q):
        return None


class _OkPool:
    def connection(self):
        return _OkConn()


class _DeadPool:
    def connection(self):
        raise RuntimeError("pool down")


class _OkRedis:
    async def ping(self):
        return True


class _DeadRedis:
    async def ping(self):
        raise ConnectionError("redis down")


class _OkQdrant:
    async def get_collections(self):
        return SimpleNamespace(collections=[])


def _request(db=None, redis=None, qdrant=None, mem0=None):
    state = SimpleNamespace(db=db or _OkPool(), redis=redis or _OkRedis(),
                            qdrant=qdrant or _OkQdrant(), mem0=mem0)
    return SimpleNamespace(app=SimpleNamespace(state=state))


async def test_status_all_healthy():
    result = await system_api.status(_request(mem0=object()), user_id="u1")
    assert result["postgres"] == {"ok": True}
    assert result["redis"] == {"ok": True}
    assert result["qdrant"] == {"ok": True}
    assert result["mem0"] is True
    assert "provider" in result["llm"]
    assert "providers" in result["mcp"]


async def test_status_dead_redis_still_returns_200_shape():
    result = await system_api.status(_request(redis=_DeadRedis()), user_id="u1")
    assert result["redis"]["ok"] is False
    assert "redis down" in result["redis"]["error"]
    assert result["postgres"]["ok"] is True  # other probes unaffected


async def test_status_dead_postgres():
    result = await system_api.status(_request(db=_DeadPool()), user_id="u1")
    assert result["postgres"]["ok"] is False


